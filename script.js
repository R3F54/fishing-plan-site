function getPreferredLanguage() {
  const stored = window.localStorage.getItem("fishing-plan-language");
  if (stored === "tr" || stored === "en") return stored;
  return navigator.language && navigator.language.toLowerCase().startsWith("tr") ? "tr" : "en";
}

function applyLanguage(language) {
  const dictionary = translations[language] || translations.en;

  document.documentElement.lang = language;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.getAttribute("data-i18n");
    if (!key || !(key in dictionary)) return;

    const value = dictionary[key];
    const attr = element.getAttribute("data-i18n-attr");
    if (attr) {
      element.setAttribute(attr, value);
      return;
    }

    if (element.hasAttribute("data-i18n-html")) {
      element.innerHTML = value;
      return;
    }

    element.textContent = value;
  });

  document.querySelectorAll("[data-i18n-title]").forEach((element) => {
    const key = element.getAttribute("data-i18n-title");
    if (!key || !(key in dictionary)) return;
    document.title = dictionary[key];
  });

  document.querySelectorAll(".lang-button").forEach((button) => {
    button.classList.toggle("is-active", button.getAttribute("data-lang") === language);
  });
}

function initScreenCarousel() {
  const carousel = document.querySelector("[data-carousel]");
  const track = document.querySelector("[data-carousel-track]");
  const dotsHost = document.querySelector("[data-carousel-dots]");
  const prevButton = document.querySelector("[data-carousel-prev]");
  const nextButton = document.querySelector("[data-carousel-next]");
  if (!carousel || !track || !dotsHost) return;

  const slides = Array.from(track.querySelectorAll("[data-carousel-slide]"));
  if (!slides.length) return;
  let activeIndex = 0;

  const scrollToSlide = (index) => {
    const safeIndex = Math.max(0, Math.min(index, slides.length - 1));
    const target = slides[safeIndex];
    if (!target) return;
    track.scrollTo({
      left: target.offsetLeft - track.offsetLeft,
      behavior: "smooth",
    });
  };

  const dots = slides.map((_, index) => {
    const button = document.createElement("button");
    button.type = "button";
    button.className = "screen-dot";
    button.setAttribute("aria-label", `Go to screen ${index + 1}`);
    button.addEventListener("click", () => scrollToSlide(index));
    dotsHost.appendChild(button);
    return button;
  });

  const setActive = () => {
    const trackCenter = track.scrollLeft + track.clientWidth / 2;
    let minDistance = Number.POSITIVE_INFINITY;
    let nextActiveIndex = 0;

    slides.forEach((slide, index) => {
      const slideCenter = slide.offsetLeft + slide.clientWidth / 2;
      const distance = Math.abs(trackCenter - slideCenter);
      if (distance < minDistance) {
        minDistance = distance;
        nextActiveIndex = index;
      }
    });

    activeIndex = nextActiveIndex;

    slides.forEach((slide, index) => {
      slide.classList.toggle("is-active", index === activeIndex);
    });
    dots.forEach((dot, index) => {
      dot.classList.toggle("is-active", index === activeIndex);
      dot.setAttribute("aria-current", index === activeIndex ? "true" : "false");
    });
  };

  prevButton?.addEventListener("click", () => {
    scrollToSlide(activeIndex - 1);
  });

  nextButton?.addEventListener("click", () => {
    scrollToSlide(activeIndex + 1);
  });

  let rafId = 0;
  track.addEventListener("scroll", () => {
    if (rafId) cancelAnimationFrame(rafId);
    rafId = requestAnimationFrame(setActive);
  }, { passive: true });

  window.addEventListener("resize", setActive);
  setActive();
}

document.addEventListener("DOMContentLoaded", () => {
  const currentLanguage = getPreferredLanguage();
  applyLanguage(currentLanguage);
  initScreenCarousel();

  document.querySelectorAll(".lang-button").forEach((button) => {
    button.addEventListener("click", () => {
      const nextLanguage = button.getAttribute("data-lang");
      if (!nextLanguage) return;
      window.localStorage.setItem("fishing-plan-language", nextLanguage);
      applyLanguage(nextLanguage);
    });
  });
});
